"""项目功能简介的固定文案。

为什么写死在代码里而不是让模型自由组织：这类「你能干什么」的回答会被
反复触发，格式一旦飘，员工看到的就是每次都不一样的介绍。这里给一份模板，
模型调 ``get_project_help`` 原样转发即可。

文案纪律：不用 emoji（P0），不用「欢迎使用」这类空话，每条都带一个真实问法。
"""

from __future__ import annotations

# 分四组：库存 / 价格 / 补货 / 订单，最后给两个可点的看板链接。
# 每组两行以内，整体控制在屏幕一屏之内。
_TEMPLATE = """**蜜可诗库存助手 · 能查什么**

**库存**
· 某个品项还有多少 —— 「冷冻芒果酱还有多少」
· 某家店有什么 —— 「新天地店有什么」
· 各门店库存状况 —— 「各家门店库存怎么样」

**价格**
· 售价和成本 —— 「芒果酱多少钱」

**补货与消耗**
· 哪些快断货了 —— 「哪些需要补货」
· 某家店缺什么 —— 「新天地店缺什么」
· 某品项近期用了多少 —— 「冷冻芒果酱最近一个月消耗多少」

**订单**
· 还没处理的 —— 「哪些订单还没处理」
· 最近的订单 —— 「最近有什么订单」

**看板（点开即是网页）**
· 预测与补货看板：{base}/forecast
· 库存健康报表：{base}/report/health

有权限且开关开启时，也可按明确的仓库、品项与数量创建入库/出库，或按单号回滚出库；回复附执行回执。下单、调拨、报损及改价请到系统里操作。"""


def build_help(base: str) -> str:
    """拼出帮助文案。``base`` 是对外可点的公网域名前缀。"""
    return _TEMPLATE.format(base=base.rstrip("/"))
